#!/usr/bin/env node
/**
 * reports/structured-data.md from a snapshot: which JSON-LD entities every URL type carries, whether
 * the graph is single and duplicate-free, and exactly what the theme merged into the Organization node.
 *   node tools/seo/structured-data-report.mjs reports/seo-after.json > reports/structured-data.md
 */
import { readFile } from 'node:fs/promises';

const snap = JSON.parse(await readFile(process.argv[2], 'utf8'));
const rows = snap.urls.filter((u) => u.jsonld);
const byType = new Map();
for (const u of rows) {
	const key = u.type || 'other';
	if (!byType.has(key)) byType.set(key, []);
	byType.get(key).push(u);
}
const nodesOf = (u) => u.jsonld.blocks_raw.flatMap((b) => (b.ok && b.data ? (b.data['@graph'] ?? [b.data]) : []));
const types = (n) => [].concat(n['@type'] ?? []);

const lines = [
	'# Structured data (JSON-LD) report',
	'',
	`Source: \`${snap.meta.base}\` (${snap.meta.mode}), ${snap.meta.generated_at}. ${rows.length} URLs. Generated by \`tools/seo/structured-data-report.mjs\`.`,
	'',
	'Yoast SEO owns the graph. The theme only merges verified LocalBusiness properties into the existing Organization node (same `@id`), never creates a second entity, and never emits ratings, reviews, offers, price ranges, coordinates or FAQ markup.',
	'',
	'## Entities per page type',
	'',
	'| Page type | URLs | JSON-LD blocks | @graph blocks | Top-level types (union) | Duplicate @id | LocalBusiness nodes |',
	'| --- | ---: | --- | --- | --- | --- | --- |',
];
for (const [t, list] of [...byType.entries()].sort()) {
	const union = new Set(list.flatMap((u) => Object.keys(u.jsonld.top_level_type_counts)));
	const dup = list.filter((u) => u.jsonld.duplicate_ids.length).length;
	const lb = Math.max(...list.map((u) => u.jsonld.top_level_type_counts.LocalBusiness ?? 0));
	lines.push(`| ${t} | ${list.length} | ${[...new Set(list.map((u) => u.jsonld.blocks))].join('/')} | ${[...new Set(list.map((u) => u.jsonld.graph_blocks))].join('/')} | ${[...union].sort().join(', ')} | ${dup} | ${lb} |`);
}

const home = rows.find((u) => u.path === '/');
const org = home && nodesOf(home).find((n) => types(n).includes('Organization'));
lines.push('', '## Organization node on the home page (after the theme merge)', '');
if (org) {
	lines.push('```json', JSON.stringify(org, null, 2), '```');
} else {
	lines.push('_No Organization node found on the home page (Yoast may be configured as a Person, or the page was not captured)._');
}

const bad = rows.filter((u) => u.jsonld.invalid || u.jsonld.duplicate_ids.length || u.jsonld.graph_blocks > 1 || (u.jsonld.top_level_type_counts.LocalBusiness ?? 0) > 1 || u.jsonld.has_aggregate_rating || u.jsonld.has_review);
lines.push('', '## Checks', '', `- URLs with invalid JSON-LD: ${rows.filter((u) => u.jsonld.invalid).length}`, `- URLs with a duplicated entity @id: ${rows.filter((u) => u.jsonld.duplicate_ids.length).length}`, `- URLs with more than one @graph block: ${rows.filter((u) => u.jsonld.graph_blocks > 1).length}`, `- URLs with more than one LocalBusiness node: ${rows.filter((u) => (u.jsonld.top_level_type_counts.LocalBusiness ?? 0) > 1).length}`, `- URLs with AggregateRating or Review markup: ${rows.filter((u) => u.jsonld.has_aggregate_rating || u.jsonld.has_review).length}`, '');
lines.push(bad.length === 0 ? '**All structured-data checks pass for the captured URLs.**' : `**${bad.length} URL(s) need attention:** ${bad.map((u) => `\`${u.path}\``).join(', ')}`, '');
lines.push('## Rich-result eligibility', '', 'Valid markup does not guarantee rich results. FAQ rich results in Google are limited to authoritative government and health sites, so the theme prints the FAQ as visible content only. Use the Rich Results Test and Search Console after go-live; nothing here is a claim about search appearance.', '');
console.log(lines.join('\n'));
