#!/usr/bin/env node
/**
 * Regenerates inc/icons-data.php from the Tabler Icons outline set (MIT licence).
 *
 *   npm pack @tabler/icons && tar xzf tabler-icons-*.tgz package/icons/outline package/LICENSE
 *   node tools/build-icons.mjs package/icons/outline
 *
 * Only the icons listed below are embedded, so the theme ships ~10 KB of inline SVG paths
 * and makes no extra network request for icons.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const src = process.argv[2];
if (!src) {
	console.error('usage: build-icons.mjs <path to @tabler/icons/icons/outline>');
	process.exit(2);
}

// theme name => tabler file name
const ICONS = {
	phone: 'phone',
	'phone-call': 'phone-call',
	pin: 'map-pin',
	map: 'map-2',
	clock: 'clock',
	search: 'search',
	menu: 'menu-2',
	close: 'x',
	'chevron-down': 'chevron-down',
	'chevron-right': 'chevron-right',
	'arrow-right': 'arrow-right',
	'arrow-up': 'arrow-up',
	check: 'check',
	shield: 'shield-check',
	wallet: 'wallet',
	bolt: 'bolt',
	day: 'calendar-event',
	week: 'calendar-week',
	month: 'calendar-month',
	user: 'user',
	share: 'share',
	link: 'link',
	document: 'file-text',
	info: 'info-circle',
	quote: 'quote',
	chat: 'message-circle',
	motorbike: 'motorbike',
	scooter: 'scooter',
	'scooter-electric': 'scooter-electric',
	bike: 'bike',
	route: 'route',
	key: 'key',
	headset: 'headset',
	store: 'building-store',
	checklist: 'clipboard-check',
	handshake: 'heart-handshake',
	external: 'external-link',
	mail: 'mail',
	badge: 'certificate',
	tripadvisor: 'brand-tripadvisor',
};

let php = `<?php
/**
 * Inline SVG icon paths (24x24, stroke based).
 *
 * GENERATED by tools/build-icons.mjs from Tabler Icons (https://tabler.io/icons),
 * Copyright (c) 2020-2024 Paweł Kuna, MIT licence (assets/icons/LICENSE-tabler-icons.txt).
 * Do not edit by hand.
 *
 * @package NguyenTu
 */

defined( 'ABSPATH' ) || exit;

/**
 * @return array<string,string> Map of icon name to inner SVG markup.
 */
function nt_icons_data(): array {
	return array(
`;

for (const [name, file] of Object.entries(ICONS)) {
	const svg = readFileSync(join(src, `${file}.svg`), 'utf8');
	const inner = svg
		.replace(/^[\s\S]*?<svg[^>]*>/, '')
		.replace(/<\/svg>\s*$/, '')
		.replace(/<path stroke="none" d="M0 0h24v24H0z" fill="none"\s*\/>/, '')
		.replace(/\s+/g, ' ')
		.trim();
	if (!inner) {
		throw new Error(`empty icon ${file}`);
	}
	php += `\t\t'${name}' => '${inner.replace(/'/g, "\\'")}',\n`;
}
php += `\t);\n}\n`;

const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'inc', 'icons-data.php');
writeFileSync(out, php);
console.log(`wrote ${out} (${Object.keys(ICONS).length} icons, ${php.length} bytes)`);
