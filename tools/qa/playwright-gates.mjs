#!/usr/bin/env node
/**
 * Maps Playwright JSON reports to release gates and records them.
 *   node tools/qa/playwright-gates.mjs reports/results/raw/pw-*.json
 * A gate fed by several report files (the contact spec runs twice: simulators on and off) only
 * passes when every contributing test passed.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';

const specs = [];
const rows = [];
function walk(suite, file) {
	const f = suite.file ?? file;
	for (const spec of suite.specs ?? []) {
		const tests = spec.tests ?? [];
		const ran = tests.filter((t) => !['skipped'].includes(t.status));
		const name = String(f ?? '').split('/').pop();
		specs.push({ file: name, title: spec.title, ran: ran.length, ok: ran.length > 0 && ran.every((t) => t.status === 'expected'), skipped: ran.length === 0 });
		for (const t of tests) rows.push({ file: name, title: spec.title, project: t.projectName ?? '', status: t.status, ms: t.results?.at(-1)?.duration ?? 0 });
	}
	for (const child of suite.suites ?? []) walk(child, f);
}
for (const file of process.argv.slice(2)) {
	const json = JSON.parse(await readFile(file, 'utf8'));
	for (const s of json.suites ?? []) walk(s, s.file);
}

// Human-readable, committed record of every browser test behind the gates.
{
	const byFile = new Map();
	for (const r of rows) {
		if (!byFile.has(r.file)) byFile.set(r.file, []);
		byFile.get(r.file).push(r);
	}
	const mark = { expected: 'PASS', unexpected: 'FAIL', skipped: 'skipped', flaky: 'FLAKY' };
	const lines = [
		'# Browser test results (Playwright, disposable sandbox)',
		'',
		`> Generated by \`tools/qa/playwright-gates.mjs\` on ${new Date().toISOString().slice(0, 10)} from the JSON reports of the last \`tools/qa/run-sandbox.sh\` run.`,
		'> Real Chromium against the disposable WordPress sandbox (synthetic content; QuickCall, MotoAI and the old-theme registration are simulators). Not production.',
		'',
		'| Spec | Tests | PASS | FAIL | skipped |',
		'| --- | ---: | ---: | ---: | ---: |',
	];
	for (const [file, list] of byFile) {
		const c = (st) => list.filter((r) => r.status === st).length;
		lines.push(`| \`${file}\` | ${list.length} | ${c('expected')} | ${c('unexpected') + c('flaky')} | ${c('skipped')} |`);
	}
	for (const [file, list] of byFile) {
		lines.push('', `## ${file}`, '', ...list.map((r) => `- ${mark[r.status] ?? r.status} — ${r.title} (${(r.ms / 1000).toFixed(1)}s)`));
	}
	await writeFile('reports/e2e-results.md', `${lines.join('\n')}\n`);
}

const GATES = {
	'e2e-layout': (s) => s.file === 'layout.spec.mjs',
	'e2e-menu': (s) => s.file === 'menu.spec.mjs',
	'e2e-contact': (s) => ['contact.spec.mjs', 'autopilot.spec.mjs'].includes(s.file),
	'e2e-woo': (s) => s.file === 'woo.spec.mjs',
	'e2e-blog': (s) => s.file === 'blog.spec.mjs',
	'e2e-seo-head': (s) => s.file === 'seo-head.spec.mjs',
	'a11y-axe': (s) => s.file === 'a11y.spec.mjs',
	'e2e-search-404': (s) => /search|404|not-found|noindex/i.test(s.title) && s.file !== 'screenshots.spec.mjs',
};
for (const [gate, pick] of Object.entries(GATES)) {
	const set = specs.filter(pick).filter((s) => !s.skipped);
	const bad = set.filter((s) => !s.ok);
	const status = set.length === 0 ? 'NOT_TESTED' : bad.length ? 'FAIL' : 'PASS';
	const detail = set.length === 0 ? 'no matching browser tests were run' : bad.length ? `${bad.length}/${set.length} failed: ${bad.slice(0, 4).map((b) => b.title).join(' | ').slice(0, 300)}` : `${set.length} browser test(s) passed`;
	execFileSync('node', ['tools/qa/record.mjs', gate, status, detail, 'reports/e2e-results.md'], { stdio: 'inherit' });
}
