#!/usr/bin/env node
/**
 * Maps a PHPUnit JUnit file to release gates (by test class / name) and records them.
 *   node tools/qa/junit-gates.mjs reports/results/integration-junit.xml
 * Skipped tests never count as a pass (see tools/qa/lib/junit.mjs).
 */
import { readFile, writeFile } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { gateResult, parseJUnit } from './lib/junit.mjs';

const cases = parseJUnit(await readFile(process.argv[2], 'utf8'));

// Human-readable, committed record of every PHPUnit integration test behind the gates.
{
	const byClass = new Map();
	for (const c of cases) {
		const k = c.cls.split('\\').pop();
		if (!byClass.has(k)) byClass.set(k, []);
		byClass.get(k).push(c);
	}
	const lines = [
		'# PHPUnit integration results (disposable WordPress sandbox)',
		'',
		`> Generated by \`tools/qa/junit-gates.mjs\` on ${new Date().toISOString().slice(0, 10)} from \`phpunit.integration.xml.dist\`. Read-only assertions against WordPress 7.1.3 + WooCommerce + Yoast with synthetic fixtures that reproduce the audit IDs. Not production.`,
		'',
		`**${cases.length} tests, ${cases.filter((c) => c.failed).length} failed, ${cases.filter((c) => c.skipped).length} skipped**`,
	];
	for (const [k, list] of byClass) {
		lines.push('', `## ${k}`, '', ...list.map((c) => `- ${c.failed ? 'FAIL' : c.skipped ? 'skipped' : 'PASS'} — ${c.name}`));
	}
	await writeFile('reports/integration-results.md', `${lines.join('\n')}\n`);
}

const GATES = {
	integration: () => true,
	'menu-36': (c) => /MenuTest/.test(c.cls),
	'categories-26': (c) => /TaxonomyTest/.test(c.cls) && /26_blog|category_urls|blog_root/.test(c.name),
	'product-terms': (c) => /TaxonomyTest/.test(c.cls) && /product_category/.test(c.name),
	'featured-items-phpunit': (c) => (/TaxonomyTest/.test(c.cls) && /featured_item_terms/.test(c.name)) || (/ContentTest/.test(c.cls) && /featured|counts_match|products_and_featured/.test(c.name)),
	'legacy-render': (c) => /LegacyRenderTest/.test(c.cls),
};

for (const [gate, pick] of Object.entries(GATES)) {
	const { status, detail } = gateResult(cases, pick);
	execFileSync('node', ['tools/qa/record.mjs', gate, status, detail, 'reports/integration-results.md'], { stdio: 'inherit' });
}
